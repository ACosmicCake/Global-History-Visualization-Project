// Year audit (report only): lists BCE records whose shown year equals the stored year, which suggests a historical
// year ("500 BCE") stored as if it were astronomical (-500). Astronomically there is a year 0, so 500 BCE is -499;
// a record storing -500 and showing "500 BCE" is a year early on the time bar. Changes no record: it writes a report
// for the records thread to work through.
// Usage: node atlas/tools/year-audit.mjs [out.md]   (default atlas/reports/year-audit-<date>.md)
import fs from 'node:fs';
import path from 'node:path';
import { ROOT, RECORDS } from './lib.mjs';

const today = new Date().toISOString().slice(0, 10);
const out = process.argv[2] || path.join(ROOT, 'reports', `year-audit-${today}.md`);
// the BCE years a display string names, in order, each as the set of years it may be: "c. 1,200 BCE", "509–27 BCE"
// (both BCE), "44 BC", and "508/507 BCE" (an Athenian or Olympiad year spanning two of ours: either)
function bceYears(display) {
  const num = x => +x.replace(/,/g, ''),
    years = [];
  for (const m of String(display || '').matchAll(/(?:(\d[\d,]*)\/)?(\d[\d,]*)(?:\s*[–-]\s*(?:(\d[\d,]*)\/)?(\d[\d,]*))?\s*(?:BCE|BC|B\.C\.E?\.?)\b/g)) {
    years.push(m[1] ? [num(m[1]), num(m[2])] : [num(m[2])]);
    if (m[4]) years.push(m[3] ? [num(m[3]), num(m[4])] : [num(m[4])]);
  }
  return years;
}
// a stored year looks historical when the shown year is the stored year and not the astronomical reading of it
const slip = (shown, y) => shown.includes(-y) && !shown.includes(1 - y);
const rows = [],
  tally = { checked: 0, consistent: 0, flagged: 0, unparsed: 0 };
for (const f of fs.readdirSync(RECORDS).filter(x => x.endsWith('.json')).sort()) {
  const r = JSON.parse(fs.readFileSync(path.join(RECORDS, f), 'utf8')),
    w = r.when || {},
    y0 = w.start?.year,
    y1 = w.end?.year;
  if (!(y0 < 0 && y0 > -100000)) continue; // historical BCE dates only; deep time is shown as years ago
  tally.checked++;
  const shown = bceYears(w.display);
  if (!shown.length) {
    tally.unparsed++;
    continue;
  }
  const hits = [],
    first = shown[0],
    last = shown[shown.length - 1];
  if (slip(first, y0)) hits.push(`start ${y0} shows as ${-y0} BCE (expected ${1 - y0} BCE, or store ${1 + y0})`);
  if (y1 < 0 && y1 !== y0 && shown.length > 1 && slip(last, y1)) hits.push(`end ${y1} shows as ${-y1} BCE (expected ${1 - y1} BCE, or store ${1 + y1})`);
  if (hits.length) {
    tally.flagged++;
    rows.push({ id: r.id, status: r.status, precision: w.precision, display: w.display, hits });
  } else tally.consistent++;
}
// coarse precision makes a one-year slip harmless; those are listed last
const fine = p => !['century', 'millennium', 'ten_millennia', 'hundred_millennia'].includes(p);
rows.sort((a, b) => fine(b.precision) - fine(a.precision) || a.id.localeCompare(b.id));
const md = `# Year audit, ${today}

Report only: no record was changed. Generated by \`node atlas/tools/year-audit.mjs\`.

A BCE record whose shown year equals its stored year (for example stored \`-500\`, shown "500 BCE") suggests a
historical year stored as if it were astronomical. Astronomical years count a year 0, so 500 BCE is \`-499\`. Such a
record sits one year early on the time bar and in sorting. Each line gives the record, its precision and what it shows;
the fix is either to store \`1 − N\` for "N BCE" or, if the stored year is right, to correct the shown text. Records at
century precision or coarser are listed last: a one-year slip does not change what they show.

- BCE records checked (years 1 to 99,999 BCE): ${tally.checked}
- Consistent (shown year = 1 − stored year): ${tally.consistent}
- Flagged: ${tally.flagged}
- Shown text names no BCE year to compare: ${tally.unparsed}

| Record | Status | Precision | Shown | Finding |
|---|---|---|---|---|
${rows.map(x => `| ${x.id} | ${x.status} | ${x.precision || ''} | ${String(x.display).replace(/\|/g, '\\|')} | ${x.hits.join('; ')} |`).join('\n')}
`;
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, md);
console.log(`year audit: ${tally.checked} BCE records checked, ${tally.flagged} flagged, ${tally.unparsed} without a BCE year to compare; wrote ${path.relative(process.cwd(), out)}`);
